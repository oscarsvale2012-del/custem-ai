function parseMore() {
  const out = [];
  for (const [category, block] of Object.entries(MORE)) {
    for (const line of block.split("\n").map((l) => l.trim()).filter(Boolean)) {
      const [title, pitch, features] = line.split("|").map((s) => s.trim());
      out.push([category, title, pitch, features || ""]);
    }
  }
  return out;
}

